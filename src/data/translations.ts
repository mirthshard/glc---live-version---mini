export const LANGUAGE_MAP: Record<LanguageCode, LanguageOption> = SUPPORTED_LANGUAGES.reduce(
  (acc, lang) => {
    acc[lang.code] = lang;
    return acc;
  },
  {} as Record<LanguageCode, LanguageOption>
);

export function isValidLanguageCode(value: string | null | undefined): value is LanguageCode {
  return Boolean(value && value in LANGUAGE_MAP);
}

